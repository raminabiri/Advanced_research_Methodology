extra<-Sys.getenv('SRMA_R_LIB','');if(nzchar(extra)).libPaths(c(extra,.libPaths()))
library(metaumbrella)
d<-read.csv('data/shared/bcg.csv')
e<-metafor::escalc(measure='RR',ai=tpos,bi=tneg,ci=cpos,di=cneg,data=d,add=0)
x<-data.frame(meta_review='Colditz1994',factor='BCG',author=as.character(d$author),year=as.character(d$year),measure='RR',value=exp(e$yi),ci_lo=exp(e$yi-1.96*sqrt(e$vi)),ci_up=exp(e$yi+1.96*sqrt(e$vi)),n_exp=d$tpos+d$tneg,n_nexp=d$cpos+d$cneg,n_cases=d$tpos+d$cpos,n_sample=d$tpos+d$tneg+d$cpos+d$cneg)
dir.create('outputs/phase5',recursive=TRUE,showWarnings=FALSE)
write.csv(x,'outputs/phase5/metaumbrella_input_BCG.csv',row.names=FALSE)
u<-umbrella(x,method.var='REML',method.esb='TESSPSST',true_effect='largest',seed=20261115)
v<-add.evidence(u,criteria='Ioannidis')
saveRDS(v,'outputs/phase5/metaumbrella_BCG.rds')
capture.output(print(v),file='outputs/phase5/metaumbrella_BCG.txt')
capture.output(str(v,max.level=2),file='outputs/phase5/metaumbrella_structure.txt')
write.csv(as.data.frame(summary(v)),'outputs/phase5/metaumbrella_summary.csv',row.names=FALSE)
capture.output(sessionInfo(),file='outputs/phase5/sessionInfo.txt')
stopifnot(length(u)==1,nrow(x)==13)
print(v)
